-- ============================================================
-- 意見募集（テーマ）にサムネイル画像を持たせる
--
-- トップページの「AIインタビュー」一覧では、テーマごとに画像を出す。
-- 施策に紐づかない抽象テーマ型でも画像を出せるようにするため、
-- 施策の thumbnail_url を借りるのではなくテーマ自身に持たせる。
-- ============================================================

alter table interview_configs
  add column thumbnail_url text;

comment on column interview_configs.thumbnail_url is 'テーマ一覧で表示する画像のURL（未設定なら紐づく施策の画像、それもなければ既定画像にフォールバックする）';
